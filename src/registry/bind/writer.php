<?php declare(strict_types=1);

namespace Moggi\Registry\Bind;

use function Moggi\Paths\moduleNameToPath;

/**
 * The writer half of `moggi bind`: a JSON descriptor from the inspector becomes
 * the layered `.mog` file a project compiles against.
 *
 * One module per library, in the established facade shape (`System.Filesystem.PHP`
 * is the model): `foreign` declarations first, then the boundary-checked public
 * face. Phase 1 collapses the two layers onto the declarations themselves — the
 * public name IS the `IO (Either String …)` / `IO (Maybe …)` declaration, so there is no raw twin
 * to reach past — and leaves hand-written overlays to ordinary
 * `[lib]` sources. The render is byte-deterministic for a descriptor: sorted
 * entries, sorted imports, no timestamps.
 */

/** One coordinate segment as a module-path segment: `foo-bar_baz` is `FooBarBaz`. */
function bindSegmentToModule(string $segment): string
{
    $word = \implode('', \array_map(
        static fn (string $part): string => \ucfirst($part),
        \preg_split('/[^A-Za-z0-9]+/', $segment) ?: [],
    ));
    if ($word === '' || \preg_match('/^[A-Za-z][A-Za-z0-9]*$/', $word) !== 1) {
        throw new \RuntimeException(
            "cannot bind `{$segment}` — it has no letters or digits to name a module with",
        );
    }

    return $word;
}

/** A host path as a Moggi string literal: backslashes escape, nothing else does. */
function moggiStringLiteral(string $path): string
{
    return '"' . \str_replace(['\\', '"'], ['\\\\', '\\"'], $path) . '"';
}

/** The bound API names in binding order: types, functions, consts. */
function bindingExports(array $types, array $functions, array $consts): array
{
    $exports = [];
    foreach (['types' => $types, 'functions' => $functions, 'consts' => $consts] as $entries) {
        foreach ($entries as $entry) {
            $exports[] = (string) $entry['moggi'];
        }
    }

    return $exports;
}

/** Every signature and type in one pool for import detection. */
function bindingSigPool(array $functions, array $consts): string
{
    return \implode("\n", \array_map(
        static fn (array $entry): string => (string) ($entry['sig'] ?? $entry['type'] ?? ''),
        [...$functions, ...$consts],
    ));
}

/**
 * The whole binding module as text, for whichever backend inspected it.
 *
 * @param array{backend: string, module: string, coordinate: string, types: list<array<string, mixed>>, functions: list<array<string, mixed>>, consts: list<array<string, mixed>>, skipped: list<array{symbol: string, reason: string}>} $descriptor
 */
function renderBinding(array $descriptor): string
{
    return match ((string) ($descriptor['backend'] ?? '')) {
        'jvm' => renderJvmBinding($descriptor),
        'dotnet' => renderDotNetBinding($descriptor),
        default => renderPhpBinding($descriptor),
    };
}

/**
 * The whole binding module as text.
 *
 * @param array{module: string, coordinate: string, types: list<array<string, mixed>>, functions: list<array<string, mixed>>, consts: list<array<string, mixed>>, skipped: list<array{symbol: string, reason: string}>} $descriptor
 */
function renderPhpBinding(array $descriptor): string
{
    $module = (string) $descriptor['module'];
    $coordinate = (string) $descriptor['coordinate'];
    $types = (array) $descriptor['types'];
    $functions = (array) $descriptor['functions'];
    $consts = (array) $descriptor['consts'];
    $skipped = (array) $descriptor['skipped'];

    $exports = bindingExports($types, $functions, $consts);

    $imports = ['Moggi.Internal.Base', 'System.IO.Base (IO)', 'Data.Either (Either(..))'];
    $pool = bindingSigPool($functions, $consts);
    foreach (['Bool' => 'Data.Bool', 'Double' => 'Data.Double', 'Int' => 'Data.Int', 'Maybe' => 'Data.Maybe', 'String' => 'Data.String'] as $word => $import) {
        if (\preg_match('/\b' . $word . '\b/', $pool) === 1) {
            $imports[] = $import;
        }
    }
    \sort($imports);

    $count = static fn (int $n, string $word): string => $n . ' ' . $word . ($n === 1 ? '' : 's');
    $lines = [
        '-- GENERATED by `moggi bind php:' . $coordinate . '` — do not edit.',
        '-- ' . $count(\count($types), 'type') . ', ' . $count(\count($functions), 'function')
            . ', ' . $count(\count($consts), 'const') . '; ' . $count(\count($skipped), 'symbol')
            . ' skipped (see --json).',
        'module ' . $module,
    ];
    if ($exports !== []) {
        $lines[] = '  ( ' . $exports[0];
        foreach (\array_slice($exports, 1) as $name) {
            $lines[] = '  , ' . $name;
        }
        $lines[] = '  ) where';
    } else {
        $lines[] = '  where';
    }
    $lines[] = '';
    foreach ($imports as $import) {
        $lines[] = 'import ' . $import;
    }
    foreach ($types as $entry) {
        $lines[] = '';
        $lines[] = 'foreign php type ' . $entry['moggi'] . ' ' . moggiStringLiteral((string) $entry['path']);
    }
    foreach ($functions as $entry) {
        $lines[] = '';
        $lines[] = 'foreign php function ' . $entry['moggi'] . ' ' . moggiStringLiteral((string) $entry['path'])
            . ' :: ' . $entry['sig'];
    }
    foreach ($consts as $entry) {
        $lines[] = '';
        $lines[] = 'foreign php const ' . $entry['moggi'] . ' ' . moggiStringLiteral((string) $entry['path'])
            . ' :: ' . $entry['type'];
    }
    $lines[] = '';

    return \implode("\n", $lines);
}

/**
 * A JVM binding module as text: raw, host-truthful, receiver-first
 * declarations — the plan's Layer 1 with no Layer 2, because the backend
 * cannot codegen an Either-wrapped foreign call.
 *
 * @param array{module: string, coordinate: string, types: list<array<string, mixed>>, functions: list<array<string, mixed>>, consts: list<array<string, mixed>>, skipped: list<array{symbol: string, reason: string}>} $descriptor
 */
function renderJvmBinding(array $descriptor): string
{
    $module = (string) $descriptor['module'];
    $coordinate = (string) $descriptor['coordinate'];
    $types = (array) $descriptor['types'];
    $functions = (array) $descriptor['functions'];
    $consts = (array) $descriptor['consts'];
    $skipped = (array) $descriptor['skipped'];

    $exports = bindingExports($types, $functions, $consts);
    $pool = bindingSigPool($functions, $consts);
    $imports = ['Moggi.Internal.Base'];
    if (\str_contains($pool, 'IO')) {
        $imports[] = 'System.IO.Base (IO)';
    }
    foreach ([
        'Bool' => 'Data.Bool',
        'Char' => 'Data.Char',
        'Double' => 'Data.Double',
        'String' => 'Data.String',
    ] as $word => $import) {
        if (\preg_match('/\b' . $word . '\b/', $pool) === 1) {
            $imports[] = $import;
        }
    }
    if (\preg_match('/\bInt8\b|\bInt16\b|\bInt32\b|\bInt64\b|\bInt\b/', $pool) === 1) {
        $imports[] = 'Data.Int';
    }
    \sort($imports);

    $count = static fn (int $n, string $word): string => $n . ' ' . $word . ($n === 1 ? '' : 's');
    $lines = [
        '-- GENERATED by `moggi bind jvm:' . $coordinate . '` — do not edit.',
        '-- ' . $count(\count($types), 'type') . ', ' . $count(\count($functions), 'function')
            . ', ' . $count(\count($consts), 'const') . '; ' . $count(\count($skipped), 'symbol')
            . ' skipped (see --json).',
        '-- A throwing method surfaces as `IO`; anything else is pure. Unchecked',
        '-- exceptions are not declared by the host, so they propagate — catch',
        '-- them with `Control.Exception` `try`/`catch`, the way hand-written',
        '-- JVM bindings do. Interfaces carry the `interface ` prefix their',
        '-- `invokeinterface` needs.',
        'module ' . $module,
    ];
    if ($exports !== []) {
        $lines[] = '  ( ' . $exports[0];
        foreach (\array_slice($exports, 1) as $name) {
            $lines[] = '  , ' . $name;
        }
        $lines[] = '  ) where';
    } else {
        $lines[] = '  where';
    }
    $lines[] = '';
    foreach ($imports as $import) {
        $lines[] = 'import ' . $import;
    }
    foreach ($types as $entry) {
        $lines[] = '';
        $lines[] = 'foreign jvm type ' . $entry['moggi'] . ' ' . moggiStringLiteral((string) $entry['path']);
    }
    foreach ($functions as $entry) {
        $lines[] = '';
        $lines[] = 'foreign jvm function ' . $entry['moggi'] . ' ' . moggiStringLiteral((string) $entry['path'])
            . ' :: ' . $entry['sig'];
    }
    foreach ($consts as $entry) {
        $lines[] = '';
        $lines[] = 'foreign jvm const ' . $entry['moggi'] . ' ' . moggiStringLiteral((string) $entry['path'])
            . ' :: ' . $entry['type'];
    }
    $lines[] = '';

    return \implode("\n", $lines);
}

