/**
 * Where the sidecar for a generated .NET module lives: the `dotnet/`
 * directory beside the module file, the shape `discoverDotNetLibDirs()`
 * scans, so the generated module and its metadata travel as one library
 * root.
 */
function dotNetBindingSidecarPath(string $outDir, string $module): string
{
    return \rtrim($outDir, '/') . '/' . \dirname(moduleNameToPath($module)) . '/dotnet/dependencies.json';
}

/**
 * Write the rendered module under `$outDir`, following the module/file law, and
 * return the path written.
 *
 * @param array{backend: string, module: string, coordinate: string, types: list<array<string, mixed>>, functions: list<array<string, mixed>>, consts: list<array<string, mixed>>, skipped: list<array{symbol: string, reason: string}>} $descriptor
 */
function writeBinding(string $outDir, array $descriptor): string
{
    $path = \rtrim($outDir, '/') . '/' . moduleNameToPath((string) $descriptor['module']) . '.mog';
    $dir = \dirname($path);
    if (!\is_dir($dir) && !@\mkdir($dir, 0777, true) && !\is_dir($dir)) {
        throw new \RuntimeException("cannot bind into `{$outDir}` — the directory cannot be created");
    }
    if (@\file_put_contents($path, renderBinding($descriptor)) === false) {
        throw new \RuntimeException("cannot bind into `{$path}` — the file cannot be written");
    }

    return $path;
}

/**
 * Write the rendered module under `$outDir`, following the module/file law, and
 * return the path written.
 *
 * @param array{module: string, coordinate: string, types: list<array<string, mixed>>, functions: list<array<string, mixed>>, consts: list<array<string, mixed>>, skipped: list<array{symbol: string, reason: string}>} $descriptor
 */
function writePhpBinding(string $outDir, array $descriptor): string
{
    return writeBinding($outDir, $descriptor + ['backend' => 'php']);
}

/**
 * Write a .NET binding: the rendered module under `$outDir`, following the
 * module/file law, plus the versioned sidecar the emitter needs beside it.
 * Returns the module path; the sidecar path is `dotNetBindingSidecarPath()`.
 *
 * @param array{module: string, coordinate: string, types: list<array<string, mixed>>, functions: list<array<string, mixed>>, consts: list<array<string, mixed>>, skipped: list<array{symbol: string, reason: string}>, sidecar: array<string, mixed>} $descriptor
 */
function writeDotNetBinding(string $outDir, array $descriptor): string
{
    $path = writeBinding($outDir, $descriptor + ['backend' => 'dotnet']);
    $sidecarPath = dotNetBindingSidecarPath($outDir, (string) $descriptor['module']);
    $dir = \dirname($sidecarPath);
    if (!\is_dir($dir) && !@\mkdir($dir, 0777, true) && !\is_dir($dir)) {
        throw new \RuntimeException("cannot bind into `{$outDir}` — the directory cannot be created");
    }
    if (@\file_put_contents($sidecarPath, \Moggi\Registry\prettyJson((array) $descriptor['sidecar']) . "\n") === false) {
        throw new \RuntimeException("cannot bind into `{$sidecarPath}` — the file cannot be written");
    }

    return $path;
}

/**
 * The bound module for a host package without inspecting anything: the name
 * the binder would give the tree `add` just resolved. The package is the
 * versionless half of the coordinate (`vendor/package`, `group:artifact`,
 * `Id`) — the tree, not the version, is what the module names.
 */
function bindModuleName(string $backend, string $package): string
{
    if ($backend === 'jvm') {
        $parts = \explode(':', $package);
        if (\count($parts) !== 2 || $parts[0] === '' || $parts[1] === '') {
            throw new \RuntimeException(
                "cannot bind `{$package}` — a Maven coordinate is `group:artifact[:version]`",
            );
        }

        return jvmBindModuleName($parts[0], $parts[1]);
    }
    if ($backend === 'dotnet') {
        if ($package === '') {
            throw new \RuntimeException(
                "cannot bind `{$package}` — a NuGet coordinate is `Id[:version]`",
            );
        }

        return dotNetBindModuleName($package);
    }
    if ($backend === 'php') {
        $parts = \explode('/', $package, 2);
        if (\count($parts) !== 2 || $parts[0] === '' || $parts[1] === '') {
            throw new \RuntimeException(
                "cannot bind `{$package}` — a Composer coordinate is `vendor/package`",
            );
        }

        return phpBindModuleName($parts[0], $parts[1]);
    }

    throw new \RuntimeException(
        "cannot bind `{$backend}:{$package}` — only `php:`, `jvm:` and `dotnet:` coordinates bind",
    );
}

/**
 * The portable name for a bound module: the ecosystem prefix is what keeps
 * three backends' bindings apart, so the facade drops it (`Maven.Com.Acme.Hello`
 * is unified as `Com.Acme.Hello`).
 */
function facadeModuleName(string $boundModule): string
{
    $segments = \explode('.', $boundModule);
    if (\count($segments) < 2) {
        throw new \RuntimeException(
            "cannot face `{$boundModule}` — a bound module names its ecosystem first",
        );
    }
    \array_shift($segments);

    return \implode('.', $segments);
}

/**
 * A portable facade skeleton over one bound module, as text: the `{-# BACKEND #-}`
 * pragma names the backend just bound, the export list is the bound API, and
 * every function and const delegates to the bound module through a qualified
 * alias, so the skeleton compiles on the bound backend today. The other two
 * backends are comment placeholders: binding them and naming them in the
 * pragma is the hand-finish this skeleton exists to receive.
 *
 * Types are imported and re-exported, never re-declared: a `foreign` type
 * belongs to the backend that declares it.
 *
 * @param array{backend: string, module: string, coordinate: string, types: list<array<string, mixed>>, functions: list<array<string, mixed>>, consts: list<array<string, mixed>>, skipped: list<array{symbol: string, reason: string}>} $descriptor
 */
function renderFacade(array $descriptor, string $facadeModule): string
{
    $backend = (string) ($descriptor['backend'] ?? '');
    $bound = (string) $descriptor['module'];
    $coordinate = (string) $descriptor['coordinate'];
    $types = (array) $descriptor['types'];
    $functions = (array) $descriptor['functions'];
    $consts = (array) $descriptor['consts'];

    $exports = bindingExports($types, $functions, $consts);
    $pool = bindingSigPool($functions, $consts);
    $imports = ['Moggi.Internal.Base'];
    if (\preg_match('/\\bIO\\b/', $pool) === 1) {
        $imports[] = 'System.IO.Base (IO)';
    }
    if (\preg_match('/\\bEither\\b/', $pool) === 1) {
        $imports[] = 'Data.Either (Either(..))';
    }
    foreach ([
        'Bool' => 'Data.Bool',
        'Char' => 'Data.Char',
        'Double' => 'Data.Double',
        'Maybe' => 'Data.Maybe',
        'String' => 'Data.String',
    ] as $word => $import) {
        if (\preg_match('/\\b' . $word . '\\b/', $pool) === 1) {
            $imports[] = $import;
        }
    }
    if (\preg_match('/\\bInt8\\b|\\bInt16\\b|\\bInt32\\b|\\bInt64\\b|\\bInt\\b/', $pool) === 1) {
        $imports[] = 'Data.Int';
    }
    \sort($imports);

    $siblings = \array_diff(['php', 'jvm', 'dotnet'], [$backend]);

    $lines = [
        '-- GENERATED binding facade for `' . $backend . ':' . $coordinate . '` — a skeleton.',
        '-- Unify the other backends by binding them and naming them in the pragma.',
        '{-# BACKEND',
        '  ' . $backend . ' = ' . $bound,
    ];
    foreach ($siblings as $sibling) {
        $lines[] = '--  ' . $sibling . ' = TODO (bind it, then name it here)';
    }
    $lines[] = '#-}';
    $lines[] = 'module ' . $facadeModule;
    if ($exports !== []) {
        $lines[] = '  ( ' . $exports[0];
        foreach (\array_slice($exports, 1) as $name) {
            $lines[] = '  , ' . $name;
        }
        $lines[] = '  ) where';
    } else {
        $lines[] = '  where';
    }
    $lines[] = '';
    $typeNames = \array_map(static fn (array $entry): string => (string) $entry['moggi'], $types);
    if ($typeNames !== []) {
        $lines[] = 'import ' . $bound . ' (' . \implode(', ', $typeNames) . ')';
    }
    $lines[] = 'import ' . $bound . ' qualified as Bound';
    foreach ($imports as $import) {
        $lines[] = 'import ' . $import;
    }
    foreach ($functions as $entry) {
        $name = (string) $entry['moggi'];
        $lines[] = '';
        $lines[] = $name . ' :: ' . $entry['sig'];
        $lines[] = $name . ' = Bound.' . $name;
    }
    foreach ($consts as $entry) {
        $name = (string) $entry['moggi'];
        $lines[] = '';
        $lines[] = $name . ' :: ' . $entry['type'];
        $lines[] = $name . ' = Bound.' . $name;
    }
    $lines[] = '';

    return \implode("\n", $lines);
}

/**
 * Write the facade skeleton under `$outDir`, following the module/file law,
 * and return the path written.
 *
 * @param array{backend: string, module: string, coordinate: string, types: list<array<string, mixed>>, functions: list<array<string, mixed>>, consts: list<array<string, mixed>>, skipped: list<array{symbol: string, reason: string}>} $descriptor
 */
function writeFacade(string $outDir, array $descriptor, string $facadeModule): string
{
    $path = \rtrim($outDir, '/') . '/' . moduleNameToPath($facadeModule) . '.mog';
    $dir = \dirname($path);
    if (!\is_dir($dir) && !@\mkdir($dir, 0777, true) && !\is_dir($dir)) {
        throw new \RuntimeException("cannot face into `{$outDir}` — the directory cannot be created");
    }
    if (@\file_put_contents($path, renderFacade($descriptor, $facadeModule)) === false) {
        throw new \RuntimeException("cannot face into `{$path}` — the file cannot be written");
    }

    return $path;
}
